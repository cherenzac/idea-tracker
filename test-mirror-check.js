'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const { score, presets } = require('./mirror-check');
assert.deepEqual(score(...presets.grounded), {direction: 2, consistentFlip: true, preserved: 2, abstains: true});
assert.deepEqual(score(...presets.sticky), {direction: 1, consistentFlip: false, preserved: 2, abstains: true});
assert.deepEqual(score(...presets.guessing), {direction: 2, consistentFlip: true, preserved: 2, abstains: false});
assert.deepEqual(score(...presets.drift), {direction: 2, consistentFlip: true, preserved: 0, abstains: true});
assert.deepEqual(score('right', 'left', 'unknown', 1, 'green'), {direction: 0, consistentFlip: true, preserved: 1, abstains: true});
assert.equal(score('unknown','right','unknown',1,'blue').consistentFlip,false);
for (const args of [['north','right','unknown',1,'blue'], ['left','right','unknown','1','blue'], ['left','right','unknown',1,'red']]) assert.throws(() => score(...args), RangeError);
const html = fs.readFileSync('fair-test.html', 'utf8');
assert.match(html, /href="#mirror-check"/); assert.match(html, /<label for="mirror-variant">/);
assert.match(html, /id="mirror-result" role="status"/); assert.match(html, /src="mirror-check\.js\?v=1"/);
const output = { textContent: '' }, select = {value:'grounded', addEventListener(name, listener) { assert.equal(name, 'change'); this.change=listener; }};
vm.runInNewContext(fs.readFileSync('mirror-check.js', 'utf8'), {document: {getElementById: id => ({'mirror-variant':select,'mirror-result':output})[id]}});
assert.match(output.textContent, /2\/2.*yes.*2\/2.*yes/);
select.value='sticky'; select.change(); assert.match(output.textContent, /1\/2.*no.*2\/2.*yes/);
select.value='guessing'; select.change(); assert.match(output.textContent, /crop: no\./);
select.value='drift'; select.change(); assert.match(output.textContent, /Preserved count and color: 0\/2/);
console.log('PASS: isolated caption checks, reversed-but-wrong claims, invalid values and wired controls.');
